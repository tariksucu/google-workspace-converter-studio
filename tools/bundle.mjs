#!/usr/bin/env node
/**
 * Writes the add-on as one script file, for the Apps Script editor without clasp (whose sign-in
 * would give it broad access to the Google account): the scripts of src/ in the order clasp pushes
 * them (by name), each under a line naming its file, after a banner with the version.
 *
 * Apps Script loads all of a project's files into one global scope, so one file holding them all
 * runs the same (test/bundle.test.mjs loads it as the editor would). The manifest stays
 * src/appsscript.json: the editor shows it as its own file (Project Settings → Show
 * "appsscript.json" manifest file in editor).
 *
 * Usage: node tools/bundle.mjs [output]   (npm run bundle)
 *   Default output: dist/converter-studio-<version>.gs, which git ignores. Never into src/: clasp
 *   would push the bundle beside the files it is made of.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, isAbsolute, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SRC, scriptFiles } from './load.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

/** The add-on's version (package.json, which src/Config.js matches: test/package.test.mjs). */
export function version() {
  return JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8')).version;
}

/** The single-file form of src/*.js. */
export function bundle() {
  const files = scriptFiles();
  const banner = [
    `// Converter Studio for Gmail and Google Drive ${version()}: the Google Workspace add-on as one file.`,
    '// GENERATED by tools/bundle.mjs from src/*.js; do not edit it, change src/ and run it again.',
    `// Files, in the order clasp pushes them: ${files.join(', ')}.`,
    '// The manifest is src/appsscript.json.',
    '',
  ].join('\n');
  const parts = files.map((name) => {
    const code = readFileSync(join(SRC, name), 'utf8').replace(/\s+$/, '');
    return `// --- src/${name} ${'-'.repeat(Math.max(3, 90 - name.length))}\n\n${code}\n`;
  });
  return `${banner}\n${parts.join('\n')}`;
}

/** Writes the bundle; refuses a path inside src/. Returns the path written. */
export function writeBundle(output) {
  const target = resolve(output ?? join(ROOT, 'dist', `converter-studio-${version()}.gs`));
  const fromSrc = relative(SRC, target);
  if (!isAbsolute(fromSrc) && fromSrc.split(sep)[0] !== '..')
    throw new Error(`${target}: not inside src/ (clasp would push it with the sources)`);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, bundle());
  return target;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    const path = writeBundle(process.argv[2]);
    console.log(`${path} (${scriptFiles().length} files, version ${version()})`);
  } catch (error) {
    console.error(error.message);
    process.exit(1);
  }
}
