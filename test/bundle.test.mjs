import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, readdirSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { test } from 'node:test';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';
import { bundle, version } from '../tools/bundle.mjs';
import { SRC, loadAddOn, scriptFiles } from '../tools/load.mjs';
import { MANIFEST } from './fakes.mjs';

const TOOL = fileURLToPath(new URL('../tools/bundle.mjs', import.meta.url));

/** The bundle loaded as the Apps Script editor loads one file: one global scope, nothing else. */
function loadBundle(text) {
  const context = vm.createContext({});
  new vm.Script(text, { filename: 'converter-studio.gs' }).runInContext(context);
  return { context, get: (name) => new vm.Script(name).runInContext(context) };
}

/** The functions Google calls by name: the manifest's, and the cards' (every 'on…' string in src/). */
function namedFunctions() {
  const common = MANIFEST.addOns.common;
  const names = new Set([
    common.homepageTrigger.runFunction,
    ...common.universalActions.filter((a) => a.runFunction).map((a) => a.runFunction),
    ...MANIFEST.addOns.gmail.contextualTriggers.map((t) => t.onTriggerFunction),
    MANIFEST.addOns.drive.onItemsSelectedTrigger.runFunction,
  ]);
  for (const name of scriptFiles())
    for (const m of readFileSync(join(SRC, name), 'utf8').matchAll(/'(on[A-Z]\w*)'/g))
      names.add(m[1]);
  return [...names].sort();
}

test('the bundle: a banner with the version, then every script in the order clasp pushes them', () => {
  const text = bundle();
  const [first, second] = text.split('\n');
  assert.equal(
    first,
    `// Converter Studio for Gmail and Google Drive ${version()}: the Google Workspace add-on as one file.`,
  );
  assert.match(second, /GENERATED by tools\/bundle\.mjs/);
  assert.equal(version(), loadAddOn().get('CS_CONFIG').version);
  const order = [...text.matchAll(/^\/\/ --- src\/(\S+\.js) -+$/gm)].map((m) => m[1]);
  assert.deepEqual(order, scriptFiles());
  assert.deepEqual(order, [...order].sort(), 'by name, as clasp pushes them');
  assert.equal(order.length, 12);
  for (const name of order) assert.ok(text.includes(readFileSync(join(SRC, name), 'utf8').trim()));
});

test('the bundle parses and defines every function the manifest and the cards name', () => {
  const single = loadBundle(bundle());
  const named = namedFunctions();
  assert.ok(named.length >= 18, named.join(' '));
  for (const name of named) assert.equal(single.get(`typeof ${name}`), 'function', name);
  // The same top-level names as the files loaded one by one.
  const files = loadAddOn();
  const functions = (context) =>
    Object.getOwnPropertyNames(context)
      .filter((n) => typeof context[n] === 'function')
      .sort();
  assert.deepEqual(functions(single.context), functions(files.context));
  for (const name of ['CS_CONFIG', 'CsApi', 'CsCards', 'CsErrors', 'CsSession', 'CsViews'])
    assert.equal(single.get(`typeof ${name}`), files.get(`typeof ${name}`), name);
});

test('npm run bundle writes the file where it is told, never into src/', () => {
  const dir = mkdtempSync(join(tmpdir(), 'gws-bundle-'));
  try {
    const out = join(dir, 'Code.gs');
    const ok = spawnSync(process.execPath, [TOOL, out], { encoding: 'utf8' });
    assert.equal(ok.status, 0, ok.stderr);
    assert.equal(readFileSync(out, 'utf8'), bundle());
    assert.match(ok.stdout, /Code\.gs \(12 files, version \d+\.\d+\.\d+\)/);

    const before = readdirSync(SRC).sort();
    const refused = spawnSync(process.execPath, [TOOL, join(SRC, 'Bundle.js')], {
      encoding: 'utf8',
    });
    assert.equal(refused.status, 1);
    assert.match(refused.stderr, /not inside src\//);
    assert.deepEqual(readdirSync(SRC).sort(), before);
    assert.ok(!existsSync(join(SRC, 'Bundle.js')));
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});
